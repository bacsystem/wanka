// @vitest-environment node
import { readFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { describe, expect, it } from "vitest";

const CONTRACT = path.resolve(__dirname, "../../../../api/openapi/openapi.yaml");
// Cabecera que agrega la CLI (`pnpm gen:api`) antes del código.
const HEADER = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const GENERATED = path.resolve(__dirname, "schema.d.ts");

describe("tipos de la API", () => {
  it("schema.d.ts coincide con apps/api/openapi/ (si falla: pnpm --filter web gen:api y commitear)", async () => {
    const ast = await openapiTS(pathToFileURL(CONTRACT));
    expect(readFileSync(GENERATED, "utf8")).toBe(HEADER + astToString(ast));
  });
});
