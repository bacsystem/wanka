-- Sin RLS: es un catálogo global, igual para todos los tenants (ADR 0001).
CREATE TABLE iam.permissions (
  -- modulo.recurso:accion; la lista de acciones es la de resources.md y el CHECK la repite para que ni una
  -- migración pueda sembrar una acción que el catálogo no define.
  code text PRIMARY KEY CONSTRAINT permissions_code_format
    CHECK (code ~ '^[a-z]+\.[a-z_]+:(read|read_all|create|update|void|export|import|approve|send|retry)$'),
  description text NOT NULL CONSTRAINT permissions_description_not_empty CHECK (description <> '')
);

